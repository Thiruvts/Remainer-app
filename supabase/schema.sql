-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.planner_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  day_number integer not null check (day_number between 1 and 60),
  completed_tasks jsonb not null default '{}'::jsonb,
  recovery_tasks jsonb not null default '[]'::jsonb,
  health jsonb not null default '{"workout":false,"sleep_hours":"","energy":"Okay"}'::jsonb,
  notes text not null default '',
  weekly_review jsonb not null default '{"wins":"","blockers":"","next_week":"","rating":"3"}'::jsonb,
  updated_at timestamptz not null default now(),
  constraint planner_progress_user_day_unique unique (user_id, day_number)
);

-- Upgrade existing installations safely by adding new columns if missing.
alter table public.planner_progress add column if not exists recovery_tasks jsonb not null default '[]'::jsonb;
alter table public.planner_progress add column if not exists weekly_review jsonb not null default '{"wins":"","blockers":"","next_week":"","rating":"3"}'::jsonb;

alter table public.planner_progress enable row level security;
drop policy if exists "Users can read their own planner progress" on public.planner_progress;
create policy "Users can read their own planner progress" on public.planner_progress for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Users can insert their own planner progress" on public.planner_progress;
create policy "Users can insert their own planner progress" on public.planner_progress for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Users can update their own planner progress" on public.planner_progress;
create policy "Users can update their own planner progress" on public.planner_progress for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Users can delete their own planner progress" on public.planner_progress;
create policy "Users can delete their own planner progress" on public.planner_progress for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.planner_progress to authenticated;
grant usage, select on sequence public.planner_progress_id_seq to authenticated;
